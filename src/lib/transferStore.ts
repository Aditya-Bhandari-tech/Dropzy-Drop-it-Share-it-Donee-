import fs from "fs";
import path from "path";

export interface StoredTransfer {
  code: string;
  files: { name: string; size: number; type: string; path?: string }[];
  totalSize: number;
  message?: string;
  createdAt: number;
  expiresAt: number;
}

// Global in-memory cache preserved across hot-reloads in Node runtime
const globalStore = global as unknown as {
  __dropzy_transfers?: Map<string, StoredTransfer>;
};

if (!globalStore.__dropzy_transfers) {
  globalStore.__dropzy_transfers = new Map<string, StoredTransfer>();

  // Sample demo transfer with pre-created real downloadable files
  const demoCode = "123456";
  const now = Date.now();
  const demoDir = path.join(process.cwd(), "uploads", demoCode);

  try {
    if (!fs.existsSync(demoDir)) {
      fs.mkdirSync(demoDir, { recursive: true });
    }

    // Write real sample files so downloads actually work on demo code!
    fs.writeFileSync(
      path.join(demoDir, "Project_Assets_2026.txt"),
      "Dropzy Transfer Demo: All project assets and documentation are ready to share.\nSlogan: Drop it, Share it, Done!\nGenerated by Dropzy."
    );
    fs.writeFileSync(
      path.join(demoDir, "Product_Roadmap_Final.txt"),
      "Product Roadmap 2026\n1. Fast 6-Digit Transfer\n2. Real-time QR Code Generation\n3. Zero Login Required\nDrop it, Share it, Done!"
    );
    fs.writeFileSync(
      path.join(demoDir, "Design_Specs.txt"),
      "Design Specifications:\nTheme: Glassmorphic Soft Sky Blue\nTypography: Geist Sans\nPrimary: Royal Blue #2563eb"
    );
  } catch (e) {
    // Ignore file write errors on init
  }

  globalStore.__dropzy_transfers.set(demoCode, {
    code: demoCode,
    files: [
      { name: "Project_Assets_2026.txt", size: 1024, type: "text/plain" },
      { name: "Product_Roadmap_Final.txt", size: 2048, type: "text/plain" },
      { name: "Design_Specs.txt", size: 1536, type: "text/plain" },
    ],
    totalSize: 4608,
    message: "Here are the project assets for review! Drop it, Share it, Done!",
    createdAt: now,
    expiresAt: now + 30 * 60 * 1000, // 30 minutes
  });
}

export const transfersMap = globalStore.__dropzy_transfers;

export function generateSixDigitCode(): string {
  let code = "";
  do {
    code = Math.floor(100000 + Math.random() * 900000).toString();
  } while (transfersMap.has(code));
  return code;
}
