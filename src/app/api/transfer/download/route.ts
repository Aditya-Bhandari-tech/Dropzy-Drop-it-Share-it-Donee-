import { NextResponse } from "next/server";
import fs from "fs/promises";
import path from "path";
import { transfersMap } from "@/lib/transferStore";

export async function GET(request: Request) {
  const { searchParams } = new URL(request.url);
  const code = searchParams.get("code")?.trim();
  const fileName = searchParams.get("file")?.trim();

  if (!code || !fileName) {
    return new NextResponse("Code and file name are required.", { status: 400 });
  }

  const transfer = transfersMap.get(code);
  if (!transfer) {
    return new NextResponse("Transfer not found or expired.", { status: 404 });
  }

  // Look for file on disk
  const safeName = path.basename(fileName);
  const filePath = path.join(process.cwd(), "uploads", code, safeName);

  try {
    const fileBuffer = await fs.readFile(filePath);
    const fileMeta = transfer.files.find((f) => f.name === safeName);
    const contentType = fileMeta?.type || "application/octet-stream";

    return new Response(new Uint8Array(fileBuffer), {
      status: 200,
      headers: {
        "Content-Disposition": `attachment; filename="${encodeURIComponent(safeName)}"`,
        "Content-Type": contentType,
        "Content-Length": fileBuffer.length.toString(),
      },
    });
  } catch (err) {
    // If not on disk, generate a fallback text file with the requested name
    const fallbackContent = `File: ${safeName}\nTransfer Code: #${code}\nGenerated by Dropzy.\nSlogan: Drop it, Share it, Done!`;
    const fallbackBuffer = Buffer.from(fallbackContent, "utf-8");

    return new Response(new Uint8Array(fallbackBuffer), {
      status: 200,
      headers: {
        "Content-Disposition": `attachment; filename="${encodeURIComponent(safeName)}"`,
        "Content-Type": "text/plain",
        "Content-Length": fallbackBuffer.length.toString(),
      },
    });
  }
}
